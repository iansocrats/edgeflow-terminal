window.EdgeFlow = window.EdgeFlow || {};

class ZeroGptDetector extends EdgeFlow.BaseDetector {
  constructor() {
    super('zerogpt', 'ZeroGPT.com Global AI Detection Standard', 80, 'ZeroGPT Deep Linguistic Sentence Classifier');
    this.endpoint = '/api/zerogpt-proxy';
    this.fallbackDirectUrl = 'https://api.zerogpt.com/api/detect/detectText';
    this.isLiveScanning = false;
    this.lastResult = null;
  }

  /**
   * Fast client-side emulation of ZeroGPT sentence-level classification
   * Evaluates sentence-by-sentence predictability and synthetic repetition.
   * @param {string} text
   * @returns {Object}
   */
  analyze(text) {
    if (!text || text.trim().length === 0) {
      return {
        fakePercentage: 0,
        humanScore: 100,
        feedback: 'No content to analyze',
        statusClass: 'green',
        aiWords: 0,
        textWords: 0,
        highlighted: [],
        isLive: false
      };
    }

    const words = this.tokenize(text);
    const textWords = words.length;
    const sentences = text.split(/(?<=[.?!])\s+/).filter(s => s.trim().length > 0);
    const highlighted = [];
    let aiWordCount = 0;

    // Check sentence by sentence against ZeroGPT detection signals
    sentences.forEach((sentence, idx) => {
      let isAiSentence = false;
      const sLower = sentence.toLowerCase();

      // Signals flagged by ZeroGPT
      if (/looking at the \d+-hour chart/i.test(sLower) && /volume/i.test(sLower)) {
        isAiSentence = true;
      } else if (/(the \d+-hour rsi sits right in the neutral zone|showing zero directional urgency)/i.test(sLower)) {
        isAiSentence = true;
      } else if (/my execution plan:\s*•/i.test(sentence)) {
        isAiSentence = true;
      } else if (/(capital protection always comes before|discipline keeps accounts alive)/i.test(sLower)) {
        isAiSentence = true;
      } else if (/^\d+\.\s+/i.test(sentence) && /(rsi|moving average|funding)/i.test(sLower)) {
        isAiSentence = true;
      }

      if (isAiSentence) {
        highlighted.push(sentence.trim());
        const sWords = sentence.split(/\s+/).filter(w => w.length > 0).length;
        aiWordCount += sWords;
      }
    });

    const fakePercentage = textWords > 0 ? Math.min(100.0, Math.round((aiWordCount / textWords) * 1000) / 10) : 0;
    const humanScore = Math.max(0, 100 - fakePercentage);

    let feedback = 'Your Text is Human Written';
    let statusClass = 'green';

    if (fakePercentage >= 50) {
      feedback = 'Your Text is AI/GPT Generated';
      statusClass = 'danger';
    } else if (fakePercentage > 15) {
      feedback = 'Your Text is Most Likely Human Written, may include parts generated by AI/GPT';
      statusClass = 'warn';
    }

    const result = {
      fakePercentage,
      humanScore,
      feedback,
      statusClass,
      aiWords: aiWordCount,
      textWords,
      highlighted,
      isLive: false
    };

    this.lastResult = result;
    return result;
  }

  /**
   * Live Query to ZeroGPT detection endpoint (via proxy or direct)
   * @param {string} text
   * @returns {Promise<Object>}
   */
  async analyzeLive(text) {
    if (!text || text.trim().length === 0) {
      return this.analyze(text);
    }

    this.isLiveScanning = true;
    try {
      let res;
      try {
        res = await fetch(this.endpoint, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ input_text: text })
        });
      } catch (proxyErr) {
        res = await fetch(this.fallbackDirectUrl, {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'Origin': 'https://www.zerogpt.com',
            'Referer': 'https://www.zerogpt.com/'
          },
          body: JSON.stringify({ input_text: text })
        });
      }

      if (res && res.ok) {
        const json = await res.json();
        if (json.success && json.data) {
          const data = json.data;
          const fakePercentage = data.fakePercentage !== undefined ? data.fakePercentage : 0;
          const humanScore = data.isHuman !== undefined ? data.isHuman : Math.max(0, 100 - fakePercentage);
          const feedback = data.feedback || (fakePercentage < 20 ? 'Your Text is Human Written' : 'Your Text is AI/GPT Generated');
          const statusClass = fakePercentage <= 15 ? 'green' : (fakePercentage <= 45 ? 'warn' : 'danger');

          const liveResult = {
            fakePercentage,
            humanScore,
            feedback,
            statusClass,
            aiWords: data.aiWords || 0,
            textWords: data.textWords || 0,
            highlighted: data.h || [],
            isLive: true
          };
          this.lastResult = liveResult;
          return liveResult;
        }
      }
    } catch (err) {
      console.warn('[ZeroGptDetector] Live scan fallback to local sentence model:', err);
    } finally {
      this.isLiveScanning = false;
    }

    const local = this.analyze(text);
    local.isLive = false;
    return local;
  }

  /**
   * Render the detector UI telemetry card
   * @param {Object} result
   */
  renderUI(result) {
    const scoreVal = document.getElementById('zeroGptHumanVal');
    const fakeVal = document.getElementById('zeroGptFakeVal');
    const wordsVal = document.getElementById('zeroGptWordsVal');
    const indicator = document.getElementById('zeroGptIndicator');
    const bar = document.getElementById('zeroGptBar');
    const statusText = document.getElementById('zeroGptStatusText');
    const diagnostics = document.getElementById('zeroGptDiagnostics');
    const bottomVerdict = document.getElementById('zeroGptVerdict');

    if (!scoreVal) return;

    // Metric 1: Human Score %
    scoreVal.textContent = `${result.humanScore}%`;
    scoreVal.className = `metric-val ${result.humanScore >= 85 ? 'real' : (result.humanScore >= 60 ? 'gold' : 'fake')}`;

    // Metric 2: Fake/AI Score %
    if (fakeVal) {
      fakeVal.textContent = `${result.fakePercentage}%`;
      fakeVal.className = `metric-val ${result.fakePercentage <= 15 ? 'real' : (result.fakePercentage <= 40 ? 'gold' : 'fake')}`;
    }

    // Metric 3: AI Words vs Total Words
    if (wordsVal) {
      wordsVal.textContent = `${result.aiWords} / ${result.textWords}`;
      wordsVal.className = `metric-val ${result.aiWords === 0 ? 'real' : 'fake'}`;
    }

    // Indicator
    if (indicator) {
      indicator.className = `det-indicator ${result.statusClass}`;
    }

    // Progress bar
    if (bar) {
      bar.style.width = `${result.humanScore}%`;
      bar.style.background = result.humanScore >= 85 ? 'var(--green, #10b981)' : (result.humanScore >= 60 ? 'var(--yellow, #f59e0b)' : 'var(--red, #ef4444)');
    }

    // Status Text
    if (statusText) {
      const liveBadge = result.isLive ? '🟢 Live API Verified (ZeroGPT.com)' : '⚡ Sentence Classifier (Live Mode Ready)';
      statusText.innerHTML = `<strong>${liveBadge}</strong> &bull; Verdict: <em>${result.feedback}</em>`;
    }

    // Diagnostics / Highlighted sentences
    if (diagnostics) {
      if (result.highlighted && result.highlighted.length > 0) {
        let html = '<div style="margin-top:6px; font-size:0.72rem; color:var(--text-dim);">';
        result.highlighted.forEach((sent, idx) => {
          html += `<div style="padding:2px 0; color:#f87171;">⚠️ <strong>Sentence ${idx + 1}</strong>: "${sent.slice(0, 90)}..."</div>`;
        });
        html += '</div>';
        diagnostics.innerHTML = html;
      } else {
        diagnostics.innerHTML = `<div style="margin-top:6px; font-size:0.72rem; color:#34d399;">
          ✅ ZeroGPT confirmed: 0 AI words detected. Clean organic phrasing.
        </div>`;
      }
    }

    // Bottom Verdict
    if (bottomVerdict) {
      if (result.humanScore >= 85) {
        bottomVerdict.innerHTML = `<span style="color:#10b981;">🛡️ ZeroGPT Standard: Passed (100% Human Authentic).</span>`;
      } else if (result.humanScore >= 60) {
        bottomVerdict.innerHTML = `<span style="color:#f59e0b;">⚠️ ZeroGPT Caution: Mixed human-AI signals detected (${result.fakePercentage}% AI).</span>`;
      } else {
        bottomVerdict.innerHTML = `<span style="color:#ef4444;">🚨 ZeroGPT Alert: AI/GPT Generated content detected. Rewrite required.</span>`;
      }
    }
  }
}

window.EdgeFlow.ZeroGptDetector = ZeroGptDetector;
